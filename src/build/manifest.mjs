// Scans pages/ and writes .orbit/manifest.tish + .orbit/entry.tish (Tish has no dynamic import).
import fs from 'node:fs'
import path from 'node:path'

const PAGE_EXT = /\.tish$/

function walk(dir, base = '') {
  const out = []
  if (!fs.existsSync(dir)) return out
  for (const name of fs.readdirSync(dir).sort()) {
    const p = path.join(dir, name)
    const rel = base ? base + '/' + name : name
    if (fs.statSync(p).isDirectory()) out.push(...walk(p, rel))
    else if (PAGE_EXT.test(name)) out.push(rel)
  }
  return out
}

export function scanPages(root) {
  const pagesDir = path.join(root, 'pages')
  const files = walk(pagesDir)
  const layouts = files.filter(f => /(^|\/)_layout\.tish$/.test(f))
  const pages = files.filter(f => !/(^|\/)_[^/]*$/.test(f))
  const layoutChain = file => {
    const chain = []
    const parts = file.split('/')
    for (let i = 0; i < parts.length; i++) {
      const dir = parts.slice(0, i).join('/')
      const l = layouts.find(l => path.dirname(l) === (dir || '.'))
      if (l) chain.push(l)
    }
    return chain
  }
  return { pages: pages.map(file => ({ file, layouts: layoutChain(file) })), layouts }
}

export function writeManifest(root) {
  const { pages, layouts } = scanPages(root)
  const dir = path.join(root, '.orbit')
  fs.mkdirSync(dir, { recursive: true })
  const cfg = fs.existsSync(path.join(root, 'orbit.config.tish')) ? '../orbit.config.tish' : (fs.existsSync(path.join(root, 'orbit.config.tishx')) ? '../orbit.config.tishx' : null)
  if (!cfg) throw new Error('orbit: missing orbit.config.tish in ' + root)
  const lines = [`// generated by orbit — do not edit`, `import * as cfg from "${cfg}"`]
  layouts.forEach((l, i) => lines.push(`import * as L${i} from "../pages/${l}"`))
  pages.forEach((p, i) => lines.push(`import * as P${i} from "../pages/${p.file}"`))
  lines.push(`export let site = cfg.site`)
  lines.push(`export let pages = [`)
  pages.forEach((p, i) => {
    const ls = p.layouts.map(l => 'L' + layouts.indexOf(l)).join(', ')
    lines.push(`  { file: ${JSON.stringify(p.file)}, mod: P${i}, layouts: [${ls}] },`)
  })
  lines.push(`]`)
  fs.writeFileSync(path.join(dir, 'manifest.tish'), lines.join('\n') + '\n')
  fs.writeFileSync(path.join(dir, 'entry.tish'), `// generated by orbit — do not edit
import { createApp, handle, collect, prerender, buildCss, loadCollections, slim, setHost as _setHost } from "@tishlang/orbit"
import * as manifest from "./manifest.tish"
export fn setHost(h) { _setHost(h) }
export fn site() { return manifest.site }
export fn create(opts) { return createApp(manifest, opts) }
export async fn serve(app, req) { return await handle(app, req) }
export async fn collectAll(res) { return await collect(res) }
export async fn prerenderAll(app, out, log) { return await prerender(app, out, log) }
export fn css(site, sources, user) { return buildCss(site, sources, user) }
export async fn content(site) { return await loadCollections(site) }
export fn slimContent(c) { return slim(c) }
`)
  return { pages, layouts }
}

// Lint: site code must not import native modules (they cannot run on the JS target).
export function lintNativeImports(root) {
  const bad = []
  const check = dir => {
    if (!fs.existsSync(dir)) return
    for (const name of fs.readdirSync(dir)) {
      const p = path.join(dir, name)
      if (fs.statSync(p).isDirectory()) { check(p); continue }
      if (!/\.tishx?$/.test(name)) continue
      const src = fs.readFileSync(p, 'utf8')
      const m = /from\s+["'](tish:[^"']+|node:[^"']+|fs|http|process|ws)["']/.exec(src)
      if (m) bad.push(`${path.relative(root, p)}: imports "${m[1]}" — use "@tishlang/orbit" runtime helpers instead`)
    }
  }
  check(path.join(root, 'pages')); check(path.join(root, 'lib')); check(path.join(root, 'components'))
  const cfg = path.join(root, 'orbit.config.tish')
  if (fs.existsSync(cfg) && /from\s+["'](tish:|node:)/.test(fs.readFileSync(cfg, 'utf8'))) bad.push('orbit.config.tish imports a native module')
  if (bad.length) throw new Error('orbit: native imports are not allowed in site code:\n  ' + bad.join('\n  '))
}
